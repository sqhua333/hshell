import type { Session } from '@shared/types'
import { isSerialSession } from '@shared/session'
import { stripAnsi } from './output-rules'

export interface RecordedEvent {
  /** Milliseconds since the recording started. */
  at: number
  direction: 'in' | 'out'
  data: string
}

export interface Recording {
  runtimeId: string
  session: Session
  startedAt: number
  stoppedAt: number
  events: RecordedEvent[]
  truncated: boolean
}

const MAX_EVENTS = 20_000
const MAX_OUTPUT_CHARS = 4 * 1024 * 1024
const MAX_INPUT_CHARS = 512 * 1024

/**
 * Captures terminal input and output while a script recording is active.
 * Connection passwords and key passphrases are handled outside the terminal
 * and cannot appear here; anything typed into the shell itself is recorded.
 */
export class Recorder {
  private state: Recording | null = null
  private outputChars = 0
  private inputChars = 0

  get active(): boolean {
    return this.state !== null
  }

  get runtimeId(): string | null {
    return this.state?.runtimeId ?? null
  }

  start(runtimeId: string, session: Session, now = Date.now()): Recording | null {
    this.state = {
      runtimeId,
      session: { ...session, auth: { ...session.auth } },
      startedAt: now,
      stoppedAt: now,
      events: [],
      truncated: false
    }
    this.outputChars = 0
    this.inputChars = 0
    return this.state
  }

  recordInput(runtimeId: string, data: string, now = Date.now()): void {
    if (!this.state || this.state.runtimeId !== runtimeId || !data) return
    this.push('in', data, now)
    this.inputChars += data.length
    if (this.inputChars > MAX_INPUT_CHARS) this.state.truncated = true
  }

  recordOutput(runtimeId: string, data: string, now = Date.now()): void {
    if (!this.state || this.state.runtimeId !== runtimeId || !data) return
    if (this.outputChars >= MAX_OUTPUT_CHARS) {
      this.state.truncated = true
      return
    }
    this.push('out', data, now)
    this.outputChars += data.length
  }

  stop(now = Date.now()): Recording | null {
    const state = this.state
    this.state = null
    if (!state) return null
    state.stoppedAt = now
    return state
  }

  private push(direction: 'in' | 'out', data: string, now: number): void {
    if (!this.state) return
    if (this.state.events.length >= MAX_EVENTS) {
      this.state.truncated = true
      return
    }
    this.state.events.push({ at: Math.max(0, now - this.state.startedAt), direction, data })
  }
}

export const recorder = new Recorder()

function sanitizeComment(text: string): string[] {
  const clean = stripAnsi(text)
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, '')
    .replace(/\r/g, '')
  const lines = clean
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
  return lines.slice(0, 3).map((line) => (line.length > 120 ? `${line.slice(0, 117)}…` : line))
}

function stepsWithComments(recording: Recording): Array<{ wait: number; data: string; comments: string[] }> {
  const steps: Array<{ wait: number; data: string; comments: string[] }> = []
  let pendingOutput: string[] = []
  let previousAt = 0
  for (const event of recording.events) {
    if (event.direction === 'out') {
      const lines = sanitizeComment(event.data)
      if (lines.length) pendingOutput.push(...lines)
      if (pendingOutput.length > 3) pendingOutput = pendingOutput.slice(-3)
      continue
    }
    const wait = Math.min(Math.max(0, event.at - previousAt), 5000)
    steps.push({ wait, data: event.data, comments: pendingOutput })
    pendingOutput = []
    previousAt = event.at
  }
  return steps
}

function formatDate(timestamp: number): string {
  return new Date(timestamp).toISOString()
}

function header(recording: Recording, runHint: string): string {
  const { session } = recording
  const target = isSerialSession(session) && session.serial
    ? `${session.serial.path} @ ${session.serial.baudRate}`
    : `${session.username}@${session.host}:${session.port}`
  return [
    '#!/usr/bin/env node',
    `// Generated by HShell on ${formatDate(recording.stoppedAt)}`,
    `// Session: ${session.name} (${target})`,
    `// Timeline: ${recording.events.filter((event) => event.direction === 'in').length} input steps, ${recording.events.length} events`,
    '// This script contains keystrokes and terminal output excerpts. Connection credentials are not included.',
    `// ${runHint}`,
    recording.truncated ? '// NOTE: the recording hit its size limit; later events were dropped.' : '',
    ''
  ]
    .filter(Boolean)
    .join('\n')
}

function stringLiteral(value: string): string {
  return JSON.stringify(value)
}

function renderSteps(steps: ReturnType<typeof stepsWithComments>): string {
  const lines = ['const steps = [']
  for (const step of steps) {
    for (const comment of step.comments) lines.push(`  // output: ${comment}`)
    lines.push(`  { wait: ${step.wait}, data: ${stringLiteral(step.data)} },`)
  }
  lines.push(']', '')
  return lines.join('\n')
}

/** Build a standalone Node.js replay script from a recording. */
export function generateReplayScript(recording: Recording): string {
  const steps = stepsWithComments(recording)
  const session = recording.session
  const serial = isSerialSession(session) ? session.serial : undefined

  if (serial) {
    const setup = [
      'import { SerialPort } from "serialport"',
      '',
      'const sleep = (ms) => new Promise((done) => setTimeout(done, ms))',
      '',
      renderSteps(steps),
      'const port = new SerialPort({',
      `  path: ${stringLiteral(serial.path)},`,
      `  baudRate: ${serial.baudRate},`,
      `  dataBits: ${serial.dataBits},`,
      `  stopBits: ${serial.stopBits},`,
      `  parity: ${stringLiteral(serial.parity)},`,
      `  flowControl: ${stringLiteral(serial.flowControl)},`,
      '  autoOpen: false',
      '})',
      '',
      'await new Promise((resolve, reject) => {',
      '  port.open((error) => (error ? reject(error) : resolve()))',
      '})',
      'for (const step of steps) {',
      '  await sleep(step.wait)',
      '  port.write(step.data)',
      '}',
      'await sleep(1000)',
      'await new Promise((resolve) => port.close(resolve))'
    ]
    return `${header({ ...recording, session: { ...session, serial } }, 'Run: npm i serialport && node this-file.mjs')}\n${setup.join('\n')}\n`
  }

  const connect = [
    `  host: process.env.HSHELL_HOST || ${stringLiteral(session.host)},`,
    `  port: Number(process.env.HSHELL_PORT || ${session.port}),`,
    `  username: process.env.HSHELL_USERNAME || ${stringLiteral(session.username)},`,
    '  ...(process.env.HSHELL_KEY',
    '    ? { privateKey: readFileSync(process.env.HSHELL_KEY) }',
    '    : { agent: process.env.SSH_AUTH_SOCK }),'
  ]
  const body = [
    'import { Client } from "ssh2"',
    'import { readFileSync } from "node:fs"',
    '',
    'const sleep = (ms) => new Promise((done) => setTimeout(done, ms))',
    '',
    renderSteps(steps),
    'const client = new Client()',
    'client.on("error", (error) => {',
    '  console.error(error.message)',
    '  process.exit(1)',
    '})',
    'client.on("ready", () => {',
    '  client.shell({ term: "xterm-256color", cols: 100, rows: 30 }, async (error, stream) => {',
    '    if (error) throw error',
    '    stream.on("data", (chunk) => process.stdout.write(chunk))',
    '    stream.stderr.on("data", (chunk) => process.stderr.write(chunk))',
    '    for (const step of steps) {',
    '      await sleep(step.wait)',
    '      stream.write(step.data)',
    '    }',
    '    stream.end()',
    '  })',
    '})',
    'client.connect({',
    connect.join('\n'),
    `  ...(process.env.HSHELL_PASSWORD ? { password: process.env.HSHELL_PASSWORD } : {})`,
    '})'
  ]
  return `${header(recording, 'Run: npm i ssh2 && node this-file.mjs (set SSH_AUTH_SOCK, HSHELL_KEY or HSHELL_PASSWORD)')}\n${body.join('\n')}\n`
}

/** Safe default file name for the save dialog. */
export function replayFileName(session: Session): string {
  const base = session.name
    .replace(/[^\p{L}\p{N}._-]+/gu, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48) || 'session'
  const stamp = new Date().toISOString().slice(0, 19).replace(/[:T]/g, '-')
  return `hshell-${base}-${stamp}.mjs`
}
